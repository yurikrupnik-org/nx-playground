fn render(header: &str, docs: &[&Y]) -> Result<String> {
    let mut out = format!("{GENERATED}\n# {header}\n");
    for (i, doc) in docs.iter().enumerate() {
        if i > 0 {
            out.push_str("---\n");
        }
        out.push_str(
            &serde_yaml_ng::to_string(doc).map_err(|e| eyre!("serialising Tekton objects: {e}"))?,
        );
    }
    Ok(out)
}

fn kustomization(cfg: &Tekton, resources: &[String]) -> String {
    let mut out = format!(
        "{GENERATED}\n\
         # Every Tekton file `butler tekton gen` writes.\n\
         apiVersion: kustomize.config.k8s.io/v1beta1\n\
         kind: Kustomization\n"
    );
    if let Some(namespace) = &cfg.namespace {
        out.push_str(&format!("namespace: {namespace}\n"));
    }
    if resources.is_empty() {
        out.push_str("resources: []\n");
    } else {
        out.push_str("resources:\n");
        for r in resources {
            out.push_str(&format!("  - {r}\n"));
        }
    }
    out
}

