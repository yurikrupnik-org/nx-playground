// Pipelines

fn runner_pipeline(cfg: &Tekton, target: &Target, name: &str) -> Y {
    let mut params: Vec<Y> = target
        .params
        .iter()
        .map(|(k, v)| param_value(k, s(v)))
        .collect();
    params.push(param_value(
        "args",
        Y::Sequence(vec![s("$(params.args[*])")]),
    ));
    let mut spec_params = clone_params(cfg);
    spec_params.push(map([
        ("name", s("args")),
        ("type", s("array")),
        ("description", s("Extra arguments after the target.")),
        ("default", Y::Sequence(Vec::new())),
    ]));
    pipeline(
        name,
        target.runner.name(),
        &target.id(),
        &target.command(),
        spec_params,
        vec![source_workspace()],
        vec![
            clone_task(),
            pipeline_task(
                "run",
                target.runner.task(),
                &["clone".to_string()],
                params,
                vec![bind(tasks::SOURCE)],
            ),
        ],
    )
}

fn deploy_pipeline(cfg: &Tekton, deploy: &Deploy, name: &str) -> Y {
    let mut steps = vec![clone_task()];
    let mut image_after = vec!["clone".to_string()];
    if !deploy.prebuild.is_empty() {
        image_after.clear();
    }
    for target in &deploy.prebuild {
        let step = format!("nx-{}", dns_chars(target));
        steps.push(pipeline_task(
            &step,
            tasks::NX,
            &["clone".to_string()],
            vec![
                param_value("project", s(&deploy.project)),
                param_value("target", s(target)),
            ],
            vec![bind(tasks::SOURCE)],
        ));
        image_after.push(step);
    }
    steps.push(pipeline_task(
        "image",
        tasks::BUILDKIT,
        &image_after,
        vec![
            param_value("image", s(&deploy.image)),
            param_value("dockerfile", s(&deploy.dockerfile)),
            param_value("context", s(&deploy.context)),
            param_value("target", s(&deploy.stage)),
            param_value(
                "build-args",
                Y::Sequence(deploy.build_args.iter().map(|a| s(a)).collect()),
            ),
        ],
        vec![bind(tasks::SOURCE), bind(tasks::DOCKERCONFIG)],
    ));
    steps.push(pipeline_task(
        "deploy",
        tasks::APPLY,
        &["image".to_string()],
        vec![
            param_value("manifest", s(&deploy.manifest)),
            param_value("image", s(&deploy.image)),
            param_value("digest", s("$(tasks.image.results.digest)")),
        ],
        vec![bind(tasks::SOURCE)],
    ));
    pipeline(
        name,
        "deploy",
        &deploy.id(),
        &format!(
            "Build {} ({}, stage {}), then apply {} pinned to its digest.",
            deploy.image, deploy.dockerfile, deploy.stage, deploy.manifest
        ),
        clone_params(cfg),
        vec![
            source_workspace(),
            map([
                ("name", s(tasks::DOCKERCONFIG)),
                (
                    "description",
                    s("Registry credentials for the push: a docker config.json."),
                ),
                ("optional", Y::Bool(true)),
            ]),
        ],
        steps,
    )
}

fn pipeline(
    name: &str,
    runner: &str,
    id: &str,
    description: &str,
    params: Vec<Y>,
    workspaces: Vec<Y>,
    tasks: Vec<Y>,
) -> Y {
    let mut labels = Mapping::new();
    labels.insert(s(RUNNER_LABEL), s(runner));
    let mut annotations = Mapping::new();
    annotations.insert(s(TARGET_ANNOTATION), s(id));
    object(
        "Pipeline",
        name,
        labels,
        annotations,
        map([
            ("description", s(description)),
            ("params", Y::Sequence(params)),
            ("workspaces", Y::Sequence(workspaces)),
            ("tasks", Y::Sequence(tasks)),
        ]),
    )
}

fn clone_params(cfg: &Tekton) -> Vec<Y> {
    let mut url = Mapping::new();
    url.insert(s("name"), s("url"));
    url.insert(s("type"), s("string"));
    url.insert(s("description"), s("Git URL to clone."));
    if let Some(repository) = &cfg.repository {
        url.insert(s("default"), s(repository));
    }
    vec![
        Y::Mapping(url),
        map([
            ("name", s("revision")),
            ("type", s("string")),
            ("description", s("Branch, tag or commit to run.")),
            ("default", s(&cfg.revision)),
        ]),
    ]
}

fn source_workspace() -> Y {
    map([
        ("name", s(tasks::SOURCE)),
        ("description", s("Scratch space for the checkout.")),
    ])
}

fn clone_task() -> Y {
    pipeline_task(
        "clone",
        tasks::CLONE,
        &[],
        vec![
            param_value("url", s("$(params.url)")),
            param_value("revision", s("$(params.revision)")),
        ],
        vec![bind(tasks::SOURCE)],
    )
}

fn pipeline_task(
    name: &str,
    task: &str,
    run_after: &[String],
    params: Vec<Y>,
    workspaces: Vec<Y>,
) -> Y {
    let mut out = Mapping::new();
    out.insert(s("name"), s(name));
    if !run_after.is_empty() {
        out.insert(
            s("runAfter"),
            Y::Sequence(run_after.iter().map(|r| s(r)).collect()),
        );
    }
    // `kind` spelled out: the admission webhook defaults it, and an object
    // that differs from its own default is re-patched on every apply.
    out.insert(s("taskRef"), map([("name", s(task)), ("kind", s("Task"))]));
    out.insert(s("params"), Y::Sequence(params));
    out.insert(s("workspaces"), Y::Sequence(workspaces));
    Y::Mapping(out)
}

fn param_value(name: &str, value: Y) -> Y {
    map([("name", s(name)), ("value", value)])
}

/// A Pipeline workspace handed to a task under the same name.
fn bind(workspace: &str) -> Y {
    map([("name", s(workspace)), ("workspace", s(workspace))])
}

/// A `tekton.dev/v1` object; every one carries the managed-by label.
fn object(kind: &str, name: &str, labels: Mapping, annotations: Mapping, spec: Y) -> Y {
    let mut all_labels = Mapping::new();
    all_labels.insert(s(MANAGED_BY), s("butler"));
    all_labels.extend(labels);
    let mut metadata = Mapping::new();
    metadata.insert(s("name"), s(name));
    metadata.insert(s("labels"), Y::Mapping(all_labels));
    if !annotations.is_empty() {
        metadata.insert(s("annotations"), Y::Mapping(annotations));
    }
    map([
        ("apiVersion", s("tekton.dev/v1")),
        ("kind", s(kind)),
        ("metadata", Y::Mapping(metadata)),
        ("spec", spec),
    ])
}

