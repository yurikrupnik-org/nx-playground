// Names and exclusions

/// Pipeline names, each claimed by exactly one target id.
#[derive(Default)]
struct Names(BTreeMap<String, String>);

impl Names {
    fn claim(&mut self, stem: &str, id: &str) -> Result<String> {
        let name = resource_name(stem, id);
        if name.is_empty() {
            bail!("target `{id}` has no characters usable in a Tekton name");
        }
        if let Some(other) = self.0.insert(name.clone(), id.to_string()) {
            bail!(
                "targets `{other}` and `{id}` both become the Pipeline `{name}`; \
                 add one to {file} [tekton] exclude",
                file = settings::FILE
            );
        }
        Ok(name)
    }
}

/// `stem` as a DNS-1123 label. Past 63 characters it is cut and suffixed with
/// a hash of the full target id, so two long ids sharing a prefix stay apart.
fn resource_name(stem: &str, id: &str) -> String {
    let name = dns_chars(stem);
    if name.len() <= MAX_NAME {
        return name;
    }
    let digest = hash::hex(&Sha256::digest(id.as_bytes()));
    // 8 hex digits plus the joining `-`; `dns_chars` output is ASCII, so any
    // byte index is a char boundary.
    let head = name[..MAX_NAME - 9].trim_end_matches('-');
    format!("{head}-{}", &digest[..8])
}

/// `[tekton] exclude`, tracking which globs matched anything.
struct Exclude<'a> {
    patterns: &'a [String],
    set: GlobSet,
    used: Vec<bool>,
}

impl<'a> Exclude<'a> {
    fn new(patterns: &'a [String]) -> Result<Self> {
        let mut builder = GlobSetBuilder::new();
        for p in patterns {
            builder.add(
                Glob::new(p).map_err(|e| {
                    eyre!("{file} [tekton] exclude `{p}`: {e}", file = settings::FILE)
                })?,
            );
        }
        Ok(Self {
            patterns,
            set: builder
                .build()
                .map_err(|e| eyre!("{file} [tekton] exclude: {e}", file = settings::FILE))?,
            used: vec![false; patterns.len()],
        })
    }

    fn hits(&mut self, id: &str) -> bool {
        let matched = self.set.matches(id);
        for &i in &matched {
            self.used[i] = true;
        }
        !matched.is_empty()
    }

    fn all_used(&self) -> Result<()> {
        let unused: Vec<&str> = self
            .patterns
            .iter()
            .zip(&self.used)
            .filter(|(_, used)| !**used)
            .map(|(p, _)| p.as_str())
            .collect();
        if !unused.is_empty() {
            bail!(
                "{file} [tekton] exclude: {} match no target; drop them",
                unused.join(", "),
                file = settings::FILE
            );
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_dns_labels_and_long_ones_stay_distinct() {
        assert_eq!(
            resource_name("nx-zerg_api-build:debug", "x"),
            "nx-zerg-api-build-debug"
        );
        let long = format!("nx-{}", "a".repeat(80));
        let a = resource_name(&format!("{long}-one"), "nx:a:one");
        let b = resource_name(&format!("{long}-two"), "nx:a:two");
        assert!(a.len() <= MAX_NAME && b.len() <= MAX_NAME, "{a} / {b}");
        assert_ne!(a, b);
    }

    #[test]
    fn two_targets_normalising_to_one_name_are_an_error() {
        let mut names = Names::default();
        names
            .claim("nx-a_b-build", "nx:a_b:build")
            .expect("first claim");
        let err = names
            .claim("nx-a-b-build", "nx:a-b:build")
            .expect_err("second claim collides");
        assert!(err.to_string().contains("nx:a_b:build"), "{err}");
    }

    #[test]
    fn exclusion_globs_cover_ids_and_a_dead_glob_is_an_error() {
        let patterns = vec!["nx:*:serve".to_string(), "task:tilt-*".to_string()];
        let mut exclude = Exclude::new(&patterns).expect("globs compile");
        assert!(exclude.hits("nx:zerg_api:serve"));
        assert!(!exclude.hits("nx:zerg_api:build"));
        let err = exclude.all_used().expect_err("task:tilt-* matched nothing");
        assert!(err.to_string().contains("task:tilt-*"), "{err}");
        assert!(exclude.hits("task:tilt-up"));
        exclude.all_used().expect("every glob matched");
    }
}
