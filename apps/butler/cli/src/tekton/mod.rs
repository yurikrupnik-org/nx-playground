const GENERATED: &str = "# GENERATED by `butler tekton gen` — DO NOT EDIT BY HAND.";

const MANAGED_BY: &str = "app.kubernetes.io/managed-by";
const RUNNER_LABEL: &str = "butler/runner";
const TARGET_ANNOTATION: &str = "butler/target";

/// Pipeline names must be DNS-1123 labels: a PipelineRun copies the name into
/// its `tekton.dev/pipeline` label, and label values stop at 63.
const MAX_NAME: usize = 63;

/// Which tool runs a target, and so which runner Task its Pipeline calls.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) enum Runner {
    Nx,
    Task,
    Just,
    Nu,
}

impl Runner {
    const fn name(self) -> &'static str {
        match self {
            Self::Nx => "nx",
            Self::Task => "task",
            Self::Just => "just",
            Self::Nu => "nu",
        }
    }

    const fn task(self) -> &'static str {
        match self {
            Self::Nx => tasks::NX,
            Self::Task => tasks::TASK,
            Self::Just => tasks::JUST,
            Self::Nu => tasks::NU,
        }
    }

    /// First comment line of the runner's Pipeline file.
    const fn source(self) -> &'static str {
        match self {
            Self::Nx => "One Pipeline per nx project:target in the project graph.",
            Self::Task => "One Pipeline per task of the root Taskfile and its local includes.",
            Self::Just => "One Pipeline per public recipe of the root justfile.",
            Self::Nu => "One Pipeline per .nu script that defines a main.",
        }
    }
}

/// One runnable target.
#[derive(Debug)]
pub(crate) struct Target {
    runner: Runner,
    /// What follows `<runner>:` in the target id: `zerg_api:build`, `check`,
    /// `db::migrate`, `scripts/nu/ide-check.nu`.
    name: String,
    /// The runner Task's params that select this target.
    params: Vec<(&'static str, String)>,
}

impl Target {
    fn id(&self) -> String {
        format!("{}:{}", self.runner.name(), self.name)
    }

    fn command(&self) -> String {
        match self.runner {
            Runner::Nx => format!("bun nx run {}", self.name),
            Runner::Task => format!("task {}", self.name),
            Runner::Just => format!("just {}", self.name),
            Runner::Nu => format!("nu --no-config-file {}", self.name),
        }
    }

    /// The Pipeline name before DNS normalisation.
    fn stem(&self) -> String {
        let name = match self.runner {
            Runner::Nu => self.name.strip_suffix(".nu").unwrap_or(&self.name),
            _ => &self.name,
        };
        format!("{}-{name}", self.runner.name())
    }
}

/// One app's build-and-deploy.
pub(crate) struct Deploy {
    /// Workload name (`zerg-api`): the rendered file's stem and the target id.
    name: String,
    project: String,
    /// Targets of `project` the image build needs first (a web app's `build`).
    prebuild: Vec<String>,
    /// The reference the rendered manifest names, e.g. `yurikrupnik/zerg-api:dev`.
    image: String,
    dockerfile: String,
    context: String,
    stage: String,
    /// `KEY=VALUE`.
    build_args: Vec<String>,
    /// Workspace-relative rendered manifest.
    manifest: String,
}

impl Deploy {
    fn id(&self) -> String {
        format!("deploy:{}", self.name)
    }
}

/// The generated files, and the stale ones in `[tekton] outDir`.
pub fn plan(
    workspace_root: &Path,
    graph: &ProjectGraph,
    root: &Root,
    overrides: &AppOverrides,
    files: &[String],
) -> Result<Plan> {
    let cfg = &root.tekton;
    let out_dir = cfg.out_dir.trim_end_matches('/').to_string();
    for (key, other) in [
        ("[k8s] outDir", k8s::out_dir(root)),
        ("[submodules] outDir", submodule::manifests::out_dir(root)),
    ] {
        if other.trim_end_matches('/') == out_dir {
            bail!(
                "{file}: [tekton] outDir and {key} are both `{out_dir}`; each generator \
                 prunes its directory, so each needs one of its own",
                file = settings::FILE
            );
        }
    }

    let mut targets = sources::nx(graph);
    targets.extend(sources::taskfile(workspace_root)?);
    targets.extend(sources::justfile(workspace_root)?);
    targets.extend(sources::nu(workspace_root, files)?);
    let mut deploys = sources::deploys(workspace_root, graph, root, overrides)?;

    let mut exclude = Exclude::new(&cfg.exclude)?;
    targets.retain(|t| !exclude.hits(&t.id()));
    deploys.retain(|d| !exclude.hits(&d.id()));
    exclude.all_used()?;

    let mut names = Names::default();
    let mut pipelines: BTreeMap<Runner, BTreeMap<String, Y>> = BTreeMap::new();
    for target in &targets {
        let name = names.claim(&target.stem(), &target.id())?;
        let doc = runner_pipeline(cfg, target, &name);
        pipelines
            .entry(target.runner)
            .or_default()
            .insert(name, doc);
    }
    let mut deploy_docs = BTreeMap::new();
    for deploy in &deploys {
        let name = names.claim(&format!("deploy-{}", deploy.name), &deploy.id())?;
        let doc = deploy_pipeline(cfg, deploy, &name);
        deploy_docs.insert(name, doc);
    }

    let mut out = BTreeMap::new();
    let mut resources = Vec::new();
    let mut emit = |file: &str, header: &str, docs: Vec<&Y>| -> Result<()> {
        out.insert(format!("{out_dir}/{file}"), render(header, &docs)?);
        resources.push(file.to_string());
        Ok(())
    };

    let task_docs = runner_tasks(cfg, &pipelines, &deploys)?;
    if !task_docs.is_empty() {
        emit(
            "tasks.yaml",
            &format!(
                "The runner Tasks the Pipelines here call. Step images: {} [tekton.images].",
                settings::FILE
            ),
            task_docs.iter().collect(),
        )?;
    }
    for (runner, docs) in &pipelines {
        emit(
            &format!("{}.yaml", runner.name()),
            runner.source(),
            docs.values().collect(),
        )?;
    }
    if !deploy_docs.is_empty() {
        emit(
            "deploy.yaml",
            "Per app with a [workload]: build its image, apply the manifest `butler k8s gen` rendered.",
            deploy_docs.values().collect(),
        )?;
    }
    out.insert(
        format!("{out_dir}/kustomization.yaml"),
        kustomization(cfg, &resources),
    );
    Plan::owned(workspace_root, out_dir, out)
}

/// The runner Tasks some generated Pipeline calls, clone first.
fn runner_tasks(
    cfg: &Tekton,
    pipelines: &BTreeMap<Runner, BTreeMap<String, Y>>,
    deploys: &[Deploy],
) -> Result<Vec<Y>> {
    if pipelines.is_empty() && deploys.is_empty() {
        return Ok(Vec::new());
    }
    let images = &cfg.images;
    let count = |runner: Runner| pipelines.get(&runner).map_or(0, BTreeMap::len);
    let mut out = vec![tasks::git_clone(image(
        images.git.as_ref(),
        "git",
        "every Pipeline's clone",
    )?)];
    if count(Runner::Nx) > 0 || deploys.iter().any(|d| !d.prebuild.is_empty()) {
        out.push(tasks::nx(image(
            images.nx.as_ref(),
            "nx",
            "the nx targets",
        )?));
    }
    if count(Runner::Task) > 0 {
        let why = format!("{} Taskfile tasks", count(Runner::Task));
        out.push(tasks::go_task(
            image(images.task.as_ref(), "task", &why)?,
            &tasks::Release {
                fetch_image: image(images.fetch.as_ref(), "fetch", &why)?,
                version: version(cfg.task_version.as_ref(), "taskVersion", &why)?,
            },
        ));
    }
    if count(Runner::Just) > 0 {
        let why = format!("{} just recipes", count(Runner::Just));
        out.push(tasks::just(
            image(images.just.as_ref(), "just", &why)?,
            &tasks::Release {
                fetch_image: image(images.fetch.as_ref(), "fetch", &why)?,
                version: version(cfg.just_version.as_ref(), "justVersion", &why)?,
            },
        ));
    }
    if count(Runner::Nu) > 0 {
        let why = format!("{} nu scripts", count(Runner::Nu));
        out.push(tasks::nu(
            image(images.nu.as_ref(), "nu", &why)?,
            &tasks::Release {
                fetch_image: image(images.fetch.as_ref(), "fetch", &why)?,
                version: version(cfg.nu_version.as_ref(), "nuVersion", &why)?,
            },
        ));
    }
    if !deploys.is_empty() {
        out.push(tasks::buildkit(image(
            images.buildkit.as_ref(),
            "buildkit",
            "the deploy Pipelines",
        )?));
        out.push(tasks::kubectl_apply(image(
            images.kubectl.as_ref(),
            "kubectl",
            "the deploy Pipelines",
        )?));
    }
    Ok(out)
}

fn image<'a>(value: Option<&'a String>, key: &str, needed_by: &str) -> Result<&'a str> {
    value.map(String::as_str).ok_or_else(|| {
        eyre!(
            "{file} [tekton.images] has no `{key}`, which {needed_by} need",
            file = settings::FILE
        )
    })
}

fn version<'a>(value: Option<&'a String>, key: &str, needed_by: &str) -> Result<&'a str> {
    value.map(String::as_str).ok_or_else(|| {
        eyre!(
            "{file} [tekton] has no `{key}`: {needed_by} need that release downloaded",
            file = settings::FILE
        )
    })
}

