// Entry point

/// Which files to write, and which app set to consider. Mirrors
/// [`crate::tilt::Selection`] so the nx plugin drives both the same way.
#[derive(Default)]
pub struct Selection<'a> {
    /// Write only this app's values files and rendered manifest.
    pub app: Option<&'a str>,
    /// Write only the aggregate `kustomization.yaml`.
    pub root_only: bool,
    /// Authoritative app directories; empty = every app with a `[workload]`.
    pub apps: &'a [String],
}

/// Generate the k8s artifacts. Returns workspace-root-relative path -> content.
pub fn generate(
    workspace_root: &Path,
    graph: &ProjectGraph,
    root: &Root,
    overrides: &AppOverrides,
    selection: &Selection<'_>,
) -> Result<BTreeMap<String, String>> {
    let mut dirs: Vec<&String> = overrides
        .iter()
        .filter(|(_, app)| app.workload.is_some())
        .map(|(dir, _)| dir)
        .collect();
    if !selection.apps.is_empty() {
        // The nx plugin's authoritative list, narrowed to the apps that deploy:
        // an image-only app is in the container set but has no workload.
        let allowed: BTreeSet<&str> = selection.apps.iter().map(String::as_str).collect();
        dirs.retain(|dir| allowed.contains(dir.as_str()));
    }
    if let Some(want) = selection.app
        && !dirs.iter().any(|dir| *dir == want)
    {
        bail!(
            "{want} deploys nothing: add a [workload] table to {want}/{file}",
            file = settings::FILE
        );
    }
    if dirs.is_empty() {
        bail!(
            "no app declares a [workload]: an app joins the k8s flow by adding \
             one to its {file}, and inherits the repo-wide shape from \
             [workloadDefaults.<kind>] in the root {file}",
            file = settings::FILE
        );
    }

    let apps: Vec<WorkloadApp> = dirs
        .iter()
        .map(|dir| resolve(workspace_root, graph, root, dir, &overrides[*dir]))
        .collect::<Result<_>>()?;

    let want_root = selection.app.is_none();
    let want_apps = !selection.root_only;

    let mut files = BTreeMap::new();
    if want_apps {
        for app in apps
            .iter()
            .filter(|a| selection.app.is_none_or(|want| a.dir == want))
        {
            let values = values_files(root, app)?;
            for (name, body) in &values {
                files.insert(format!("{}/k8s/{name}", app.dir), body.clone());
            }
            files.insert(
                format!("{}/{}.yaml", out_dir(root), app.name),
                render(root, app, &values)?,
            );
        }
    }
    if want_root {
        files.insert(
            format!("{}/kustomization.yaml", out_dir(root)),
            kustomization(root, &apps),
        );
    }
    Ok(files)
}

