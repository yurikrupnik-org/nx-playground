// Rendering through the package

/// The `kcl run` invocation that turns values files into manifests — one
/// spelling, shared by `butler k8s gen` and the Tiltfile it renders, so the dev
/// loop and the committed manifests cannot come from different packages.
pub(crate) fn render_command(root: &Root) -> String {
    format!("kcl run \"{}\" -D env={} -q", package_ref(root), root.env)
}

fn package_ref(root: &Root) -> String {
    match &root.k8s.tag {
        Some(tag) => format!("{}?tag={tag}", root.k8s.package),
        None => root.k8s.package.clone(),
    }
}

/// Render one app through the package.
///
/// The values files go to a scratch directory first, so `gen` and `--check`
/// render from exactly the bytes butler just computed — never from a stale
/// values file, and never disturbed by a leftover `kcl.mod` in the app tree.
fn render(root: &Root, app: &WorkloadApp, values: &BTreeMap<String, String>) -> Result<String> {
    let scratch = Scratch::new(&app.name)?;
    for (name, body) in values {
        std::fs::write(scratch.0.join(name), body)
            .map_err(|e| eyre!("writing {name} for {}: {e}", app.dir))?;
    }

    let package = package_ref(root);
    let output = Command::new("kcl")
        .arg("run")
        .arg(&package)
        .arg("-D")
        .arg(format!("env={}", root.env))
        .arg("-q")
        .current_dir(&scratch.0)
        .output()
        .map_err(|e| {
            eyre!(
                "running `kcl` for {}: {e}\n\
                 the k8s artifacts are rendered by the {package} KCL package; \
                 install kcl (https://kcl-lang.io) to generate them",
                app.dir
            )
        })?;

    let stderr = String::from_utf8_lossy(&output.stderr);
    if !output.status.success() {
        bail!(
            "{}: `{}` failed ({}):\n{}",
            app.dir,
            render_command(root),
            output.status,
            stderr.trim_end()
        );
    }
    let manifests = String::from_utf8_lossy(&output.stdout);
    if manifests.trim().is_empty() {
        bail!(
            "{}: `{}` rendered nothing — the [workload] payload produced no \
             objects.{}",
            app.dir,
            render_command(root),
            if stderr.trim().is_empty() {
                String::new()
            } else {
                format!("\n{}", stderr.trim_end())
            }
        );
    }

    Ok(format!(
        "{GENERATED}\n\
         # Source: {file} [workload], rendered by {package} (env {env}).\n\
         {manifests}",
        file = app.file,
        env = root.env,
    ))
}

/// The aggregate: one entry per rendered app, so `kubectl apply -k` or an
/// ArgoCD application points at a single directory.
///
/// `[k8s] extraResources` is appended verbatim. It exists for objects that are
/// environment fixtures rather than workload shape — the dev-only placeholder
/// Secrets, for instance, which the package cannot render (it emits
/// ExternalSecrets) and which would otherwise scatter dummy credentials across
/// every app's config.
fn kustomization(root: &Root, apps: &[WorkloadApp]) -> String {
    let mut names: Vec<&str> = apps.iter().map(|a| a.name.as_str()).collect();
    names.sort_unstable();
    let mut out = format!(
        "# GENERATED by `butler k8s gen --root` — DO NOT EDIT BY HAND.\n\
         # One entry per app with a [workload] in its {file}, plus the\n\
         # [k8s] extraResources that file lists.\n\
         apiVersion: kustomize.config.k8s.io/v1beta1\n\
         kind: Kustomization\n\
         resources:\n",
        file = settings::FILE,
    );
    for name in names {
        let _ = writeln!(out, "  - {name}.yaml");
    }
    for extra in &root.k8s.extra_resources {
        let _ = writeln!(out, "  - {extra}");
    }
    out
}

/// A directory that exists only for the duration of one render.
struct Scratch(PathBuf);

impl Scratch {
    fn new(name: &str) -> Result<Self> {
        use std::sync::atomic::{AtomicU32, Ordering};
        static SEQ: AtomicU32 = AtomicU32::new(0);
        let dir = std::env::temp_dir().join(format!(
            "butler-k8s-{}-{}-{name}",
            std::process::id(),
            SEQ.fetch_add(1, Ordering::Relaxed),
        ));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir)
            .map_err(|e| eyre!("creating a render scratch dir at {}: {e}", dir.display()))?;
        Ok(Self(dir))
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

