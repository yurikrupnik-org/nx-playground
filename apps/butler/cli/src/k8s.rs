//! `butler k8s gen` — the values files an app deploys from, and the manifests
//! the published `app` KCL package renders from them.
//!
//! One config surface, one renderer. An app declares a `[workload]` in its
//! `butler.toml` and nothing else: no `values.yaml` to keep in step, no
//! `main.k`, no `kcl.mod`, no kustomize overlay. `butler k8s gen` writes
//!
//! ```text
//! <app>/k8s/values.yaml          the merged workload, one per app
//! <app>/k8s/values.<env>.yaml    that environment's diffs, one per env
//! manifests/k8s/apps/<name>.yaml the rendered objects
//! manifests/k8s/apps/kustomization.yaml
//! ```
//!
//! and `--check` fails when any of them has drifted, exactly like the
//! Tiltfiles.
//!
//! ## Pass-through, not modelling
//!
//! `[workload]`, `[externalSecret]` and their per-env overlays are opaque TOML:
//! butler serialises them to YAML 1:1 and never enumerates a schema key. The
//! KCL package owns the schema and is what rejects an unknown or mistyped
//! field, so a package release adds fields without a butler release. See
//! [`crate::settings::Root::workload_defaults`].
//!
//! ## What butler does own
//!
//! The `image` reference, which must have exactly one home: the image facts
//! ([`crate::tilt::image_facts`]) that also drive the Tiltfile's
//! `docker_build` and CI's `container` target. A workload table that declares
//! `image` is a hard error, not an override — that is the duplication this
//! whole flow exists to kill.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use eyre::{Result, bail, eyre};
use toml::Value;
use toml::value::Table;

use crate::graph::ProjectGraph;
use crate::settings::{self, App, AppEnv, AppOverrides, Root};
use crate::tilt;

/// Where every rendered manifest lands, workspace-root-relative: root
/// `butler.toml` `[k8s] outDir`, with `{env}` expanded so a repo that renders
/// several environments can keep them side by side
/// (`outDir = "manifests/k8s/{env}"`).
///
/// `[k8s] extraResources` entries are relative to this directory, so moving it
/// to a different depth means fixing those paths too — the generated aggregate
/// lives here and kustomize resolves them from it.
pub fn out_dir(root: &Root) -> String {
    root.k8s.out_dir.replace("{env}", &root.env)
}

/// The container port the KCL package's `Workload` schema defaults to. Spelled
/// here because Tilt has to forward to the port the app will actually listen
/// on, and an app that takes the default declares no `port` at all.
pub(crate) const DEFAULT_PORT: u16 = 8080;

const GENERATED: &str = "# GENERATED by `butler k8s gen` — DO NOT EDIT BY HAND.";

