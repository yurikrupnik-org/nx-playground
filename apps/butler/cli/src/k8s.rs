// Values files

/// Every values file one app needs, keyed by bare filename.
fn values_files(root: &Root, app: &WorkloadApp) -> Result<BTreeMap<String, String>> {
    reject_declared_image(root, app)?;
    let mut out = BTreeMap::new();
    out.insert("values.yaml".to_string(), values_for(root, app, None)?);
    for env in app.envs.keys() {
        out.insert(
            format!("values.{env}.yaml"),
            values_for(root, app, Some(env))?,
        );
    }
    Ok(out)
}

/// One values file. `env = None` is the base `values.yaml`: the fully merged
/// workload, tagged for the repo's default environment. `Some(env)` is the
/// `values.<env>.yaml` overlay, which carries only that environment's diffs
/// plus its own image tag — the package deep-merges it over the base, so
/// restating the base there would only be a second place to keep in step.
fn values_for(root: &Root, app: &WorkloadApp, env: Option<&str>) -> Result<String> {
    let overlay = env.and_then(|e| app.envs.get(e));
    let mut workload = match env {
        None => merge(
            root.workload_defaults.get(app.kind.name()),
            Some(&app.declared),
            None,
        ),
        Some(_) => overlay
            .and_then(|o| o.workload.clone())
            .unwrap_or_else(|| Value::Table(Table::new())),
    };
    let table = workload
        .as_table_mut()
        .ok_or_else(|| eyre!("{}: [workload] must be a table", app.file))?;

    let active = env.unwrap_or(&root.env);
    table.insert(
        "image".to_string(),
        Value::String(image_ref(root, app, active)),
    );
    if env.is_none() {
        // Defaults, not decrees: an app that spells one of these out keeps it.
        for (key, value) in [
            ("name", &app.name),
            ("namespace", &app.product),
            ("partOf", &app.product),
        ] {
            table
                .entry(key.to_string())
                .or_insert_with(|| Value::String(value.clone()));
        }
    }

    let (config, external_secret) = match overlay {
        Some(o) => (o.config.as_ref(), o.external_secret.as_ref()),
        None => (app.config.as_ref(), app.external_secret.as_ref()),
    };

    let mut release = serde_yaml_ng::Mapping::new();
    release.insert(yaml_key("workload"), to_yaml(&workload));
    if let Some(config) = config {
        let data: serde_yaml_ng::Mapping = config
            .iter()
            .map(|(k, v)| (yaml_key(k), serde_yaml_ng::Value::String(v.clone())))
            .collect();
        release.insert(yaml_key("config"), serde_yaml_ng::Value::Mapping(data));
    }
    if let Some(secret) = external_secret {
        release.insert(yaml_key("externalSecret"), to_yaml(secret));
    }

    let body = serde_yaml_ng::to_string(&serde_yaml_ng::Value::Mapping(release)).map_err(|e| {
        eyre!(
            "{}: serialising values for {app_env}: {e}",
            app.file,
            app_env = env.unwrap_or("the base")
        )
    })?;
    Ok(format!("{}\n{body}", header(app, env)))
}

fn header(app: &WorkloadApp, env: Option<&str>) -> String {
    match env {
        None => format!(
            "{GENERATED}\n# Source: {file} [workload] over {root} \
             [workloadDefaults.{kind}].",
            file = app.file,
            root = settings::FILE,
            kind = app.kind.name(),
        ),
        Some(env) => format!(
            "{GENERATED}\n# Source: {file} [env.{env}] — diffs the package \
             deep-merges over values.yaml.",
            file = app.file,
        ),
    }
}

/// The one key butler refuses to take from a workload table.
///
/// The image reference has a single home — the app's `[image]` or the root
/// `[imageDefaults.<kind>]` — and butler stamps it in per environment from
/// there, so the Tiltfile, CI and the manifest can never name three different
/// images. Every layer that could smuggle one in is checked, and the error
/// names the file and the table to edit.
fn reject_declared_image(root: &Root, app: &WorkloadApp) -> Result<()> {
    let declares = |value: Option<&Value>| {
        value
            .and_then(Value::as_table)
            .is_some_and(|t| t.contains_key("image"))
    };
    let kind = app.kind.name();
    let sources: [(bool, String, String); 2] = [
        (
            declares(root.workload_defaults.get(kind)),
            settings::FILE.to_string(),
            format!("[workloadDefaults.{kind}]"),
        ),
        (
            declares(Some(&app.declared)),
            app.file.clone(),
            "[workload]".to_string(),
        ),
    ];
    for (declared, file, table) in sources {
        if declared {
            return Err(image_is_not_yours(&file, &table));
        }
    }
    for (env, overlay) in &app.envs {
        if declares(overlay.workload.as_ref()) {
            return Err(image_is_not_yours(
                &app.file,
                &format!("[env.{env}.workload]"),
            ));
        }
    }
    Ok(())
}

fn image_is_not_yours(file: &str, table: &str) -> eyre::Report {
    eyre!(
        "{file}: {table} declares `image`, which butler owns. The reference is \
         derived from the app's `[image]` or the root `[imageDefaults.<kind>]` \
         plus the environment's tag, so that the Tiltfile, CI and the rendered \
         manifest cannot name three different images. Remove the key."
    )
}

// ---------------------------------------------------------------------------
// TOML -> YAML

fn yaml_key(key: &str) -> serde_yaml_ng::Value {
    serde_yaml_ng::Value::String(key.to_string())
}

/// TOML value -> YAML value, 1:1. The conversion is explicit rather than
/// `Serialize`-driven so that TOML's date/time literals — which have no
/// counterpart in the package's schema — reach KCL as the text the author
/// wrote instead of serde's private tagged representation.
fn to_yaml(value: &Value) -> serde_yaml_ng::Value {
    use serde_yaml_ng::Value as Y;
    match value {
        Value::String(s) => Y::String(s.clone()),
        Value::Integer(i) => Y::Number((*i).into()),
        Value::Float(f) => Y::Number((*f).into()),
        Value::Boolean(b) => Y::Bool(*b),
        Value::Datetime(d) => Y::String(d.to_string()),
        Value::Array(items) => Y::Sequence(items.iter().map(to_yaml).collect()),
        Value::Table(table) => Y::Mapping(
            table
                .iter()
                .map(|(k, v)| (yaml_key(k), to_yaml(v)))
                .collect(),
        ),
    }
}

