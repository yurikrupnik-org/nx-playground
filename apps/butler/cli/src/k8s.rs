    /// Environment fixtures the package cannot render ride along in the
    /// aggregate; nothing else may inject a resource into it.
    #[test]
    fn extra_resources_are_appended_after_the_apps() {
        let mut only = app("replicas = 1");
        only.name = "zerg-api".into();
        // `extraResources` belongs to `[k8s]`, so it cannot ride on the shared
        // `root()` helper: that appends after `[k8s.imageTag]`.
        let cfg: Root = toml::from_str(
            "registry = 'acme'\n\
             [k8s]\ntag = '0.1.2'\nextraResources = ['../dev/app-secrets.yaml']\n",
        )
        .expect("test root config parses");
        assert_eq!(
            kustomization(&cfg, &[only])
                .lines()
                .skip_while(|l| *l != "resources:")
                .collect::<Vec<_>>(),
            vec![
                "resources:",
                "  - zerg-api.yaml",
                "  - ../dev/app-secrets.yaml"
            ]
        );
    }

