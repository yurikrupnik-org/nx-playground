// Resolution

/// An app that deploys something: everything the values files need, with the
/// workload payload still opaque.
struct WorkloadApp {
    /// Workspace-root-relative app directory.
    dir: String,
    /// `<dir>/butler.toml`, for error messages that name where to make the fix.
    file: String,
    /// Image basename (`todo-web-htmx`) — the workload name, the Tilt resource
    /// and the rendered file's stem, all one string.
    name: String,
    /// Image repository with the registry substituted and no tag.
    repository: String,
    /// Product segment of the app path; the namespace and `partOf`.
    product: String,
    kind: tilt::Kind,
    /// The app's own `[workload]`, verbatim.
    declared: Value,
    config: Option<BTreeMap<String, String>>,
    external_secret: Option<Value>,
    /// Every environment this app gets a values file for: the ones it declares
    /// plus every one the repo knows. An environment with no diffs still needs
    /// a file — the package hard-errors on a missing overlay for `-D env=`.
    envs: BTreeMap<String, AppEnv>,
}

fn resolve(
    workspace_root: &Path,
    graph: &ProjectGraph,
    root: &Root,
    dir: &str,
    app: &App,
) -> Result<WorkloadApp> {
    let project = graph
        .projects
        .values()
        .find(|p| p.root == *dir)
        .ok_or_else(|| eyre!("{dir} declares a [workload] but is not a discovered project"))?;
    let kind = tilt::app_kind(workspace_root, dir).ok_or_else(|| {
        eyre!(
            "{dir}: no {markers}; unsupported app kind",
            markers = tilt::KIND_MARKERS
        )
    })?;
    let facts = tilt::image_facts(root, &kind, dir, project, app.image.as_ref())?;
    let repository = tilt::image_from_tag(&facts.tag, &root.registry);
    let name = repository
        .rsplit('/')
        .next()
        .filter(|s| !s.is_empty())
        .ok_or_else(|| eyre!("{dir}: cannot derive a workload name from image `{repository}`"))?
        .to_string();

    let mut envs: BTreeMap<String, AppEnv> = app.env.clone();
    for env in repo_envs(root) {
        envs.entry(env).or_default();
    }

    Ok(WorkloadApp {
        dir: dir.to_string(),
        file: format!("{dir}/{}", settings::FILE),
        name,
        repository,
        product: product(dir),
        kind,
        declared: app
            .workload
            .clone()
            .expect("callers filter on a declared workload"),
        config: app.config.clone(),
        external_secret: app.external_secret.clone(),
        envs,
    })
}

/// Every environment the repo deploys: the default one plus every one that
/// pins an image tag.
fn repo_envs(root: &Root) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    out.insert(root.env.clone());
    out.extend(root.k8s.image_tag.keys().cloned());
    out
}

/// The product an app belongs to: the segment below `apps/`
/// (`apps/todo/api` -> `todo`), else the app directory name, else `default` for
/// a single-app repo. The namespace, `partOf` and Tilt's KCL render all use it,
/// so it is derived once.
pub(crate) fn product(dir: &str) -> String {
    dir.split('/')
        .nth(1)
        .or_else(|| dir.split('/').next_back())
        .filter(|s| !s.is_empty() && *s != ".")
        .unwrap_or("default")
        .to_string()
}

/// The image an environment deploys: the repository the image facts own, tagged
/// with what the root `[k8s.imageTag]` maps that environment to — its own name
/// when it maps nothing, so `dev` renders `:dev` unconfigured.
fn image_ref(root: &Root, app: &WorkloadApp, env: &str) -> String {
    let tag = root.k8s.image_tag.get(env).map_or(env, String::as_str);
    format!("{}:{tag}", app.repository)
}

// ---------------------------------------------------------------------------
// Merging

/// Deep, right-wins merge — the same semantics the KCL package uses to layer
/// `values.<env>.yaml` over `values.yaml`, and kustomize to layer an overlay
/// over a base: nested tables merge recursively, scalars and arrays replace
/// wholesale, and a key only the right side has is added.
///
/// Arrays replace rather than append because appending has no useful inverse:
/// an environment that needs one fewer `env` entry could not express it.
pub(crate) fn merge(
    defaults: Option<&Value>,
    app: Option<&Value>,
    overlay: Option<&Value>,
) -> Value {
    let mut out = Value::Table(Table::new());
    for layer in [defaults, app, overlay].into_iter().flatten() {
        merge_into(&mut out, layer);
    }
    out
}

fn merge_into(base: &mut Value, over: &Value) {
    match (base, over) {
        (Value::Table(into), Value::Table(from)) => {
            for (key, value) in from {
                match into.get_mut(key) {
                    Some(existing) => merge_into(existing, value),
                    None => {
                        into.insert(key.clone(), value.clone());
                    }
                }
            }
        }
        (base, over) => *base = over.clone(),
    }
}

/// The workload an app deploys in one environment: the repo-wide shape for its
/// kind, its own `[workload]`, that environment's `[env.<env>.workload]`.
/// `None` when the app declares no workload at all.
///
/// Shared with the Tiltfile renderer, which needs the merged `port` to compose
/// `port_forwards`.
pub(crate) fn merged_workload(
    root: &Root,
    app: &App,
    kind: tilt::Kind,
    env: &str,
) -> Option<Value> {
    let declared = app.workload.as_ref()?;
    Some(merge(
        root.workload_defaults.get(kind.name()),
        Some(declared),
        app.env.get(env).and_then(|e| e.workload.as_ref()),
    ))
}

/// The container port a merged workload listens on, mirroring the package's own
/// default for a workload that declares none.
pub(crate) fn workload_port(workload: &Value) -> u16 {
    workload
        .get("port")
        .and_then(Value::as_integer)
        .and_then(|p| u16::try_from(p).ok())
        .unwrap_or(DEFAULT_PORT)
}

